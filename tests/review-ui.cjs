/* Synthetic controller/API only; no model, microphone, or live service. */
'use strict';
const assert = require('assert/strict');
const fs = require('fs');
const path = require('path');
const Review = require('../static/review.js');
const clone = (v) => JSON.parse(JSON.stringify(v));
function storage() { const map = new Map(); return { get length() { return map.size; }, key(i) { return [...map.keys()][i] ?? null; }, getItem(k) { return map.get(k) ?? null; }, setItem(k, v) { map.set(k, String(v)); }, removeItem(k) { map.delete(k); } }; }
const session = (id) => ({ id, title: '微观经济学', segments: [{ id: 'S1', version: 1, text: '<script>unsafe</script>', start: 10, end: 20, audio_seq: 0 }], slides: [], audio: [{ seq: 0, start: 8, duration: 20 }], review: { marks: [], runs: [], cards: [], notes: [], selected_note_id: null, selection_revision: 0 } });
(async () => {
  const store = storage(), calls = []; let gate = null, failure = null, found = null;
  const api = async (url, options = {}) => { calls.push({ url, body: options.body && clone(options.body) }); if (gate) await gate; if (failure) throw failure; if (url.includes('/requests/')) { if (found) return found; throw Object.assign(new Error('missing'), { status: 404 }); } if (url.endsWith('/draft')) return { id: 'N1', user_draft: { ...options.body, revision: options.body.revision + 1 } }; return { id: 'R1', status: 'prepared', evidence: { segments: [], slides: [] } }; };
  const c = Review.createController({ api, storage: store, tabId: 'tab-a' });
  c.sync(session('A')); assert.equal(c.session.id, 'A');
  let release; gate = new Promise((r) => { release = r; });
  const preparing = c.prepare({ scope: 'all', card_types: ['concept'] });
  c.sync(session('B')); release(); await preparing; gate = null;
  assert.equal(c.session.id, 'B'); assert.equal(c.review.runs.length, 0, 'late prepare never enters another class');
  assert.equal(calls.at(-1).body.session_id, 'A');
  c.sync(session('A'));
  failure = new Error('lost response');
  await assert.rejects(c.prepare({ scope: 'all', card_types: ['concept'] }));
  assert.ok(c.pending(), 'ambiguous response persists recovery receipt');
  const writes = calls.filter((x) => x.body).length;
  const restarted = Review.createController({ api, storage: store, tabId: 'tab-b' }); restarted.sync(session('A'));
  assert.ok(restarted.pending()); failure = null;
  await restarted.recover();
  assert.equal(calls.filter((x) => x.body).length, writes, 'recovery only looks up; never resends');
  await assert.rejects(restarted.retryPending(false), /请确认/);
  const lostRequest = clone(restarted.pending());
  await restarted.retryPending(true);
  assert.deepEqual(calls.at(-1).body, lostRequest.body, 'explicit retry preserves exact body and request ID');
  failure = new Error('second lost response'); await assert.rejects(restarted.prepare({ scope: 'all' })); failure = null;
  found = { kind: 'prepare', item_id: 'R1', run: { id: 'R1', status: 'prepared' } }; await restarted.recover();
  assert.equal(restarted.pending(), null);
  assert.equal(restarted.review.runs[0].id, 'R1');
  store.setItem('classroom-review-request-v1:A:another-page', JSON.stringify({ request_id: 'another-page', operation: 'prepare', type: 'runs', path: '/api/review/prepare', body: { session_id: 'A', request_id: 'another-page' } }));
  assert.equal(restarted.pending()?.request_id, 'another-page', 'parallel tab receipts have separate durable keys');
  await restarted.recover(); assert.equal(restarted.pending(), null);
  restarted.writeDraft('note', 'N1', { revision: 2, content: 'my words', personal_note: 'mine' });
  failure = Object.assign(new Error('version conflict'), { status: 409 });
  await assert.rejects(restarted.saveDraft('note', 'N1'));
  assert.equal(restarted.draft('note', 'N1').content, 'my words', 'CAS conflict keeps typed content');
  const other = Review.createController({ api, storage: store, tabId: 'tab-c' }); other.sync(session('A'));
  other.writeDraft('note', 'N1', { revision: 2, content: 'other tab', personal_note: '' });
  assert.equal(restarted.draft('note', 'N1').content, 'my words', 'tab drafts do not overwrite each other');
  assert.equal(other.drafts().length, 2, 'both drafts remain recoverable');
  failure = null; gate = new Promise((r) => { release = r; });
  const saving = other.saveDraft('note', 'N1');
  other.writeDraft('note', 'N1', { revision: 2, content: 'typed during save', personal_note: '' });
  other.sync(session('B')); release(); await saving; gate = null;
  other.sync(session('A'));
  assert.equal(other.draft('note', 'N1').content, 'typed during save');
  assert.equal(other.draft('note', 'N1').revision, 3, 'next autosave uses acknowledged CAS revision');
  const html = fs.readFileSync(path.join(__dirname, '../static/index.html'), 'utf8');
  for (const id of ['review-view','review-open','review-back','review-plan-dialog','review-editor-dialog','review-package-dialog']) assert.ok(html.includes(`id="${id}"`), id);
  assert.ok(!Review.sourceHTML(session('A'), { segments: session('A').segments }).includes('<script>unsafe'));
  assert.match(Review.sourceHTML(session('A'), { segments: session('A').segments }), /#t=2/);
  assert.doesNotMatch(Review.sourceHTML({ ...session('A'), audio_deleted_at: 'now' }, { segments: session('A').segments }), /<audio/);
  const missingAudio = Review.sourceHTML(session('A'), { segments: session('A').segments }, { audio: [{ source_id: 'S1', available: false, reason: '录音文件损坏' }] });
  assert.doesNotMatch(missingAudio, /<audio/); assert.match(missingAudio, /录音文件损坏/);
  const restoredAudio = Review.sourceHTML(session('copy-B'), { segments: session('A').segments, source_session_id: 'A' }, { audio: [{ source_id: 'S1', available: true, offset: 3, url: '/api/audio/0?session_id=A' }] });
  assert.match(restoredAudio, /session_id=copy-B#t=3/); assert.doesNotMatch(restoredAudio, /session_id=A/);
  const beforeUnknown = calls.length;
  await assert.rejects(other.send({ id: 'Runknown', status: 'unknown' }), /重复计费/);
  assert.equal(calls.length, beforeUnknown, 'unknown billing requires explicit confirmation before any send');
  await assert.rejects(other.send({ id: 'Rchanged', status: 'prepared', source_status: { changed: true } }), /原快照/);
  const deniedStore = { getItem() { return null; }, setItem() { throw new Error('quota'); } };
  const denied = Review.createController({ api, storage: deniedStore }); denied.sync(session('A'));
  await assert.rejects(denied.prepare({ scope: 'all' }), /无法持久保存/);
  const invalid = session('invalid'); invalid.review = { read_only: true, error: '复习格式不可用' };
  other.sync(invalid); const beforeReadonly = calls.length;
  await assert.rejects(other.prepare({ scope: 'all' }), /复习格式不可用/);
  assert.equal(calls.length, beforeReadonly, 'damaged review remains read-only');
  console.log('review-ui passed: class isolation, durable request lookup, CAS draft retention, tab-local drafts, source safety/audio offsets (synthetic)');
})().catch((e) => { console.error(e); process.exitCode = 1; });
