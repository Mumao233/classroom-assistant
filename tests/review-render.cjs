const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const path = require('node:path');
const root = path.join(__dirname, '..');
const sandbox = {window: {}, console};
sandbox.window.katex = require(path.join(root, 'static/vendor/katex/katex.min.js'));
vm.createContext(sandbox);
vm.runInContext(fs.readFileSync(path.join(root, 'static/review-render.js'), 'utf8'), sandbox);
const R = sandbox.window.ReviewRender;
let checks = 0;
const check = fn => { fn(); checks += 1; };
check(() => assert.match(R.render('中文 English 😀'), /中文 English 😀/));
check(() => assert.match(R.render('**重点** `原文`'), /<strong>重点<\/strong>/));
check(() => assert.doesNotMatch(R.render('<script>alert(1)</script>'), /<script/));
check(() => assert.match(R.render('</script><img src=x onerror=alert(1)>'), /&lt;img/));
check(() => assert.doesNotMatch(R.render('[x](javascript:alert(1))'), /<a/));
check(() => assert.match(R.render('$Q_s = 10 + 2P$'), /class="katex"/));
check(() => assert.match(R.render('$$\n\\frac{a}{b} = 2\n$$'), /katex-display/));
check(() => assert.match(R.render('\\(P^*=5\\)'), /class="katex"/));
check(() => assert.match(R.render('$\\unknowncommand{x}$'), /公式无法渲染/));
check(() => assert.match(R.render('$\\href{https://evil.invalid}{x}$'), /公式无法渲染/));
check(() => assert.doesNotMatch(R.render('$\\href{https://evil.invalid}{x}$'), /<a/));
check(() => assert.doesNotMatch(R.render('$\\htmlStyle{background:url(https://evil.invalid)}{x}$'), /style="background/));
check(() => assert.match(R.render('$$x\n未闭合'), /保留原文/));
check(() => assert.match(R.render('`$x$`'), /<code>\$x\$<\/code>/));
check(() => assert.match(R.render('```\n<script>\n```'), /<pre><code>&lt;script&gt;/));
check(() => assert.equal(R.time(3661.2), '61:01'));
check(() => assert.equal(R.time(null), '时间未知'));
check(() => assert.equal(R.escape('"\'&<>'), '&quot;&#39;&amp;&lt;&gt;'));
check(() => assert.match(R.render('$' + 'x'.repeat(4001) + '$'), /公式无法渲染/));
check(() => { const saved = sandbox.window.katex; sandbox.window.katex = null; assert.match(R.render('$x$'), /公式无法渲染/); sandbox.window.katex = saved; });
console.log(`review-render: ${checks} checks passed (real offline KaTeX; no browser/network)`);
